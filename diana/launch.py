def domain_name(idea: str) -> str:
    """حوزهٔ کسب‌وکار را از واژه‌ای می‌گیرد که زودتر در جمله آمده است."""
    t = idea or ""
    best = None
    for key, name in DOMAIN_NAMES:
        pos = t.find(key)
        if pos >= 0 and (best is None or pos < best[0]):
            best = (pos, name)
    if best:
        return best[1]
    base = _guess_name(idea)
    return base if base != "کسب‌وکار من" else "کسب‌وکار جدید"


def parse_launch_text(text: str) -> dict:
    """استخراج ورودی‌ها از جملهٔ آزاد فرمانده (مثلاً از چت)"""
    raw = (text or "").strip()
    f = dict(DEFAULTS)
    f["idea"] = raw[:600]
    m = re.search(r"در\s+([آ-یA-Za-z]{3,20})", raw)
    if m:
        f["city"] = m.group(1)
    m = re.search(r"اسم(?:ش|‌ش)?\s*(?:رو|را)?\s*[«\"]?([^»\"،.\s]{3,25})", raw)
    if m:
        f["business_name"] = m.group(1)
    m = re.search(r"(\d+)\s*(?:تا|الی)\s*(\d+)\s*مشتری", raw)
    if m:
        f["customers"] = m.group(2)
    m = re.search(r"(\d+)\s*مشتری", raw)
    if m:
        f["customers"] = m.group(1)
    m = re.search(r"(\d+(?:[.,]\d+)?)\s*(?:میلیون|هزار)", raw)
    if m:
        f["ticket"] = m.group(1)
    return normalize_fields(f)


