def numbers(L: dict) -> dict:
    ticket = _num(L["ticket"], 5)
    customers = max(1, _int(L["customers"], 20))
    cap = max(1, _int(L["capacity"], 30))
    conv = min(90.0, max(1.0, _num(L["conversion"], 5)))
    cac = _num(L["cac"], 0.4)
    revenue = ticket * customers
    leads = math.ceil(customers / (conv / 100.0))
    respond = 0.15
    meetings = max(1, math.ceil(leads * respond))
    marketing = cac * customers
    profit = revenue - marketing
    cap_pct = (customers / cap) * 100.0
    per_day = math.ceil(leads / 22.0)
    payback = (marketing / revenue * 100) if revenue else 0
    return {
        "ticket": ticket, "customers": customers, "capacity": cap, "conv": conv, "cac": cac,
        "revenue": revenue, "leads": leads, "meetings": meetings, "marketing": marketing,
        "profit": profit, "cap_pct": cap_pct, "per_day": per_day, "payback": payback,
        "cur": L.get("currency") or "تومان",
    }


def money(x: float, cur: str) -> str:
    if abs(x - round(x)) < 0.05:
        return f"{fa(round(x))} میلیون {cur}" if round(x) else f"صفر {cur}"
    return f"{fa(round(x, 2))} میلیون {cur}"


def capacity_note(n: dict) -> str:
    if n["cap_pct"] <= 80:
        return (f"✅ ظرفیت اجرا کافی است: {fa(n['customers'])} سفارش از {fa(n['capacity'])} ظرفیت "
                f"({fa(round(n['cap_pct']))}٪ اشغال).")
    if n["cap_pct"] <= 100:
        return (f"⚠️ ظرفیت تقریباً پر است ({fa(round(n['cap_pct']))}٪). یک تأمین‌کنندهٔ پشتیبان اضافه کن "
                f"یا قیمت را بالا ببر.")
    return (f"🛑 هدف از ظرفیت بیشتر است ({fa(round(n['cap_pct']))}٪). قبل از فروش، ظرفیت را با تأمین‌کنندهٔ "
            f"دوم بالا ببر وگرنه دیر تحویل دادن، اعتبارت را می‌سوزاند.")


