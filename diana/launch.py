FA_DIGITS = "۰۱۲۳۴۵۶۷۸۹"


def fa(n) -> str:
    """تبدیل عدد به رقم فارسی"""
    return str(n).replace(".", "٫").translate(str.maketrans("0123456789", FA_DIGITS))


def _num(v, default=0.0):
    try:
        s = str(v).replace("٫", ".").replace("٬", "").replace(",", "")
        s = s.translate(str.maketrans(FA_DIGITS, "0123456789"))
        return float(s)
    except Exception:
        return default


def _int(v, default=0):
    return int(round(_num(v, default)))


