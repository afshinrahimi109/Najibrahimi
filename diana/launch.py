def normalize_fields(fields: dict) -> dict:
    """پاک‌سازی و تکمیل ورودی‌های فرمانده"""
    out = dict(DEFAULTS)
    for k, v in (fields or {}).items():
        if k in out and v not in (None, ""):
            out[k] = v
    out["idea"] = re.sub(r"\s+", " ", str(out.get("idea") or "")).strip()[:600]
    out["business_name"] = str(out.get("business_name") or "").strip()[:60]
    out["target"] = str(out.get("target") or "").strip()[:160]
    out["ticket"] = _num(out.get("ticket"), 5.0) or 5.0
    out["customers"] = max(1, _int(out.get("customers"), 20))
    out["capacity"] = max(1, _int(out.get("capacity"), 30))
    out["conversion"] = min(90.0, max(1.0, _num(out.get("conversion"), 5.0)))
    out["cac"] = max(0.0, _num(out.get("cac"), 0.4))
    out["suppliers"] = [s.strip() for s in re.split(r"[،,\n;]+", str(out.get("suppliers") or "")) if s.strip()][:12]
    out["need_suppliers"] = bool(out.get("need_suppliers", True))
    if not out["business_name"]:
        out["business_name"] = domain_name(out["idea"])
    if not out["goal"]:
        out["goal"] = (f"راه‌اندازی «{out['business_name']}» در {out['city'] or 'شهر خودم'} و رسیدن به "
                       f"{fa(out['customers'])} قرارداد در ماه")
    return out


