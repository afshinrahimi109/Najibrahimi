class LaunchEngine:
    """موتور راه‌اندازی: برنامه می‌سازد، ۷ مرحله را با ایجنت‌ها اجرا می‌کند و همه را ذخیره می‌کند."""

    def __init__(self, memory, emit, llm=None):
        self.memory = memory
        self.emit = emit or (lambda e: None)
        self.llm = llm

    # ---------- کمکی ----------
    def _pub_agent(self, a):
        return {k: a.get(k) for k in ("id", "fa", "en", "emoji", "dept", "dept_fa", "dept_emoji", "color", "executor", "desc")}

    def _save(self, name, content):
        try:
            return tools.vault_write(name, content)
        except Exception:
            return name

    def _live_attempt(self, agent, stage, L):
        """اجرای واقعی با مغز ابری رایگان؛ در نبود اینترنت None برمی‌گرداند."""
        if not self.llm:
            return None
        try:
            if not tools.internet_available():
                return None
            if self.llm.mode().startswith("local"):
                return None
        except Exception:
            return None
        pb = stage_playbook(stage["id"], L)
        prompt = (
            f"کسب‌وکار: «{L['business_name']}» — {L['idea']}\n"
            f"بازار: {L['city'] or 'شهر مشتری'} | کانال: {L['channel']} | واحد پول: {L['currency']}\n"
            f"مرحله: {stage['step']} | خروجی مورد نیاز: {stage['deliverable']}\n"
            f"چارچوب داخلی: {'; '.join(pb['tasks'][:3])}\n"
            "خروجی: یک سند اجرایی فارسی Markdown، حداکثر ۶۰۰ کلمه، شامل اقدام‌های مشخص با عدد و مهلت، "
            "اسکریپت/متن آمادهٔ استفاده، KPI و دو ریسک با پادزهر. از کلی‌گویی پرهیز کن."
        )
        try:
            txt, src = self.llm.generate(prompt, system=(
                f"تو {agent['fa']} ({agent['en']}) در دپارتمان راه‌اندازی کسب‌وکار دیانا هستی. "
                f"تخصصت: {agent['desc']}. فقط خروجی نهایی و کاربردی بده."))
        except Exception:
            return None
        if txt and len(txt.strip()) > 120:
            return txt.strip(), src or "cloud"
        return None

    # ---------- ثبت ----------
    def _record(self, L, plan_md):
        lid = "L" + str(int(time.time() * 1000))[-9:]
        rec = {
            "id": lid, "fields": L, "plan": plan_md, "status": "planning",
            "stages": [{"id": s["id"], "step": s["step"], "icon": s["icon"], "owner": s["owner"],
                        "deliverable": s["deliverable"], "status": "pending"} for s in STAGES],
            "results": [], "score": None, "report_file": "", "automation": automation_specs(L),
            "ts": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
        }
        self.memory.add_launch(rec)
        return rec

    def detail(self, lid, full: bool = False) -> dict:
        rec = self.memory.get_launch(lid)
        if not rec:
            return None
        out = dict(rec)
        if not full:
            out["results"] = [
                {**{k: v for k, v in r.items() if k != "output"}, "output": (r.get("output") or "")[:1600]}
                for r in rec.get("results", [])
            ]
        return out

    def public(self, rec):
        if not rec:
            return None
        out = dict(rec)
        out.pop("results", None)
        return out

    def start(self, fields: dict, mode: str = "auto") -> dict:
        """برنامه را می‌سازد و اجرای ۷ مرحله را در پس‌زمینه آغاز می‌کند."""
        L = normalize_fields(fields)
        plan_md = plan_markdown(L)
        rec = self._record(L, plan_md)
        plan_file = self._save(f"launch-{rec['id']}-00-plan.md", plan_md)
        # اسناد آمادهٔ استفاده: پیش‌نویس قرارداد و قالب RFQ تأمین‌کننده
        contract_file = self._save(f"launch-{rec['id']}-contract-draft.md", contract_markdown(L))
        rfq_file = self._save(f"launch-{rec['id']}-rfq-template.md", rfq_markdown(L))
        rec["plan_file"] = plan_file
        rec["contract_file"] = contract_file
        rec["rfq_file"] = rfq_file
        self.memory.update_launch(rec["id"], plan_file=plan_file, contract_file=contract_file,
                                  rfq_file=rfq_file, status="running")
        self.emit({"type": "launch_created", "launch": self.public(rec)})
        threading.Thread(target=self._run, args=(rec["id"], L, mode), daemon=True).start()
        return self.public(rec)

    def _run(self, lid, L, mode="auto"):
        try:
            results = []
            total = len(STAGES)
            for i, stage in enumerate(STAGES):
                agent = AGENT_BY_ID.get(stage["owner"]) or AGENT_BY_ID.get("launch-01")
                self._mark_stage(lid, i, "running")
                self.emit({"type": "launch_stage_started", "launch_id": lid, "index": i,
                           "total": total, "stage": {"id": stage["id"], "step": stage["step"],
                                                     "icon": stage["icon"], "deliverable": stage["deliverable"]},
                           "agent": self._pub_agent(agent)})
                live = self._live_attempt(agent, stage, L) if mode != "offline" else None
                if live:
                    output, source = live
                    output = stage_markdown(stage, L, agent) + "\n### 🧠 تحلیل زندهٔ متخصص\n\n" + output
                else:
                    output = stage_markdown(stage, L, agent)
                    source = "playbook"
                score, verdict = self.evaluate(stage, output, source)
                content = (f"# {stage['icon']} {stage['step']} — {L['business_name']}\n\n"
                           f"*مرحلهٔ {fa(i + 1)} از {fa(total)} | متخصص: {agent['emoji']} {agent['fa']} | "
                           f"منبع: {'مغز ابری + کتاب راهنما' if source != 'playbook' else 'کتاب راهنمای اجرایی دیانا'} | "
                           f"امتیاز ارزیاب: {fa(score)}/۱۰۰ ({verdict})*\n\n{output}\n")
                fname = self._save(f"launch-{lid}-{i + 1:02d}-{stage['id']}.md", content)
                res = {"index": i, "stage": {"id": stage["id"], "step": stage["step"], "icon": stage["icon"],
                                             "deliverable": stage["deliverable"]},
                       "agent": self._pub_agent(agent), "output": output, "score": score,
                       "verdict": verdict, "source": source,
                       "artifact": {"name": fname, "type": "file"}}
                results.append(res)
                self._mark_stage(lid, i, "done", score=score, verdict=verdict,
                                 source=source, artifact=fname, preview=output[:4000])
                self.memory.update_launch(lid, results=[self._brief(r) for r in results], status="running")
                self.emit({"type": "launch_progress", "launch_id": lid, "done": i + 1, "total": total})
                self.emit({"type": "launch_stage_done", "launch_id": lid, "index": i, "total": total,
                           "stage": res["stage"], "agent": res["agent"], "score": score,
                           "verdict": verdict, "source": source, "artifact": res["artifact"],
                           "preview": output[:1400]})
                time.sleep(0.35)

            runbook = runbook_markdown(L, results, f"launch-{lid}-runbook.md")
            report_file = self._save(f"launch-{lid}-runbook.md", runbook)
            auto_file = self._save(f"launch-{lid}-automation.md", automation_markdown(L))
            score = round(sum(r["score"] for r in results) / max(1, len(results)))
            self.memory.update_launch(lid, status="done", results=[self._brief(r) for r in results],
                                      score=score, report=runbook, report_file=report_file,
                                      automation_file=auto_file,
                                      contract_file=f"launch-{lid}-contract-draft.md",
                                      rfq_file=f"launch-{lid}-rfq-template.md")
            self.emit({"type": "launch_ready", "launch_id": lid, "score": score,
                       "report_file": report_file, "automation_file": auto_file,
                       "automation": automation_specs(L), "stages": total,
                       "report": runbook[:5000]})
            self.memory.log_chat("diana",
                                 f"کسب‌وکار «{L['business_name']}» راه‌اندازی شد: {fa(total)} مرحله، "
                                 f"امتیاز کیفی {fa(score)}/۱۰۰، {fa(len(automation_specs(L)))} قاعدهٔ اتوماسیون، "
                                 f"گزارش در {report_file}", "launch")
        except Exception as e:
            try:
                self.memory.update_launch(lid, status="failed", report=f"خطا: {e}")
                self.emit({"type": "launch_failed", "launch_id": lid, "error": str(e)})
            except Exception:
                pass

    def _mark_stage(self, lid, index, status, **extra):
        """وضعیت هر مرحله را برای نمایش زنده در رابط کاربری به‌روز می‌کند."""
        rec = self.memory.get_launch(lid)
        if not rec:
            return
        stages = [dict(s) for s in rec.get("stages", [])]
        if 0 <= index < len(stages):
            stages[index].update({"status": status, **extra})
        self.memory.update_launch(lid, stages=stages)

    @staticmethod
    def _brief(r):
        return {"index": r["index"], "stage": r["stage"], "agent": r["agent"], "score": r["score"],
                "verdict": r["verdict"], "source": r["source"], "artifact": r["artifact"]}

    def evaluate(self, stage, output, source):
        score = 55
        notes = ["کتاب راهنمای اجرایی"]
        if len(output) > 900:
            score += 12
        if len(output) > 2000:
            score += 8
        if all(k in output for k in ("KPI", "ریسک", "کارهای این مرحله")):
            score += 10
            notes.append("دارای اقدام/KPI/ریسک")
        if "«" in output:
            score += 5
            notes.append("متن آمادهٔ استفاده")
        if source != "playbook":
            score += 8
            notes.append("تحلیل زندهٔ مغز ابری")
        score = max(0, min(100, score))
        level = "عالی 🌟" if score >= 88 else "خوب ✅" if score >= 75 else "قابل قبول 👍"
        return score, f"{level} — {'، '.join(notes)}"
