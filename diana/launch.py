def _guess_name(idea: str) -> str:
    words = [w.strip("»«\"'،؛:.!?") for w in re.split(r"[\s،.؛:!?]+", idea or "")]
    words = [w for w in words if len(w) > 2 and w not in STOP and not w.endswith("ه") or
             (len(w) > 3 and w not in STOP)]
    words = [w for w in words if w not in STOP]
    return " ".join(words[:2]) if words else "کسب‌وکار من"


