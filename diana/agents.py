def find_agents(query: str, k: int = 5):
    """یافتن بهترین ایجنت‌ها برای یک درخواست با امتیازدهی IDF و ریشه‌یابی فارسی"""
    q = norm(query)
    tokens = [t for t in re.split(r"[\s،؛,.؟!()\[\]«»\"']+", q) if len(t) > 1]
    boosts = {}
    for pattern, ids in BOOST_RULES:
        if re.search(pattern, q):
            for aid in ids:
                boosts[aid] = boosts.get(aid, 0) + 14.0
    scored = []
    for a in AGENTS:
        score = boosts.get(a["id"], 0.0)
        if norm(a["fa"]) in q or (a["en"] and a["en"].lower() in q):
            score += 15.0
        for term in set(norm(a["keywords"]).split()):
            m = _term_match(term, tokens)
            if m:
                score += m * _idf(term)
        if score > 0:
            scored.append((score, a))
    scored.sort(key=lambda x: -x[0])
    return [a for _, a in scored[:k]]

