import math as _math

# وزن‌دهی IDF: کلمات کلیدی نادرتر (مثل «پایتون») امتیاز بیشتری از کلمات رایج (مثل «برنامه») می‌گیرن
_DF = {}
for _a in AGENTS:
    for _term in set(norm(_a["keywords"]).split()):
        _DF[_term] = _DF.get(_term, 0) + 1
_N = len(AGENTS)

def _idf(term):
    return _math.log((_N + 1) / (_DF.get(term, 0) + 1)) + 1.0

def _term_match(term, tokens):
    """تطبیق دقیق یا ریشه‌ای (پیشوندی) — برای پوشش صرف فعل‌های فارسی مثل بنویس/بنویسی/بنویسید"""
    if len(term) < 3 and term.isascii() is False:
        return 0.0  # واژه‌های فارسی دو حرفی مثل «ای» نویز ایجاد می‌کنن
    best = 0.0
    for t in tokens:
        if t == term:
            return 3.0
        if len(term) >= 3 and len(t) >= 3 and (t.startswith(term) or term.startswith(t)):
            best = max(best, 2.0)
    return best

# قواعد تقویتی دامنه‌ای: ترکیب فعل+مفعول فارسی مستقیماً متخصص درست رو فعال می‌کنه
