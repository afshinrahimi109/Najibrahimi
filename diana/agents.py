def build_registry():
    agents = []
    for dept_id, dept_fa, dept_emoji, color, members in DEPARTMENTS:
        for i, (fa, en, emoji, keywords, executor, desc) in enumerate(members, 1):
            agents.append({
                "id": f"{dept_id}-{i:02d}",
                "fa": fa, "en": en, "emoji": emoji,
                "keywords": keywords, "executor": executor, "desc": desc,
                "dept": dept_id, "dept_fa": dept_fa, "dept_emoji": dept_emoji, "color": color,
            })
    return agents

