import re

def norm(s: str) -> str:
    """نرمال‌سازی متن فارسی/عربی برای جستجو و تطبیق"""
    if not s:
        return ""
    s = s.lower()
    s = s.replace("ي", "ی").replace("ك", "ک").replace("ة", "ه").replace("ؤ", "و")
    s = s.replace("إ", "ا").replace("أ", "ا").replace("‌", " ").replace("‏", "")
    s = re.sub(r"[ً-ٰٟ]", "", s)
    return s.strip()

